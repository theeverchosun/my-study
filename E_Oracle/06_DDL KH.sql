/*
제약조건 테이블의 특정 컬럼에 부적절한 데이터가 들어오지 못하도록 설정하는 규칙
데이터 무결성 (정확성 일관성 신뢰성)을 보장하는것이 목적
설정 방식 종류
1 컬럼 레벨 방식 :  컬럼 정의 바로 옆에 제약조건을 기술하는 방식(모든 제약조건 설정 가능)
2 테이블 레벨 방식 : 모든 컬럼 정의을 마친후  하단에 별도로 기술하는 방식(NOT NULL제외)
*/
/*
NOT NULL 제약조건
해당 컬럼에 NULL값이 저장될수 업도록 제한
:필수적으로 입력되어야하는 데이터 아이디 비밀번호 연락처 등에 지정
=> 컬럼 레벨 방식으로만 지정할수있음
*/
---회원(MEMBER_NOTNULL) : 회원번호 (MEM_NO) 회원 아이디(MEM_ID) 비밀번호 (MEM_PWD) 이름(MEM_NAME) NOT NULL제약조건 설정
CREATE TABLE MEMBER_NOTNULL ( 
MEM_NO NUMBER NOT NULL,
MEM_ID VARCHAR2(20) NOT NULL,
MEM_PWD VARCHAR2(20) NOT NULL,
MEM_NAME VARCHAR2(20) NOT NULL,
GENDER CHAR(3),
PHONE CHAR(15),
EMAIL VARCHAR2(41),
ENROLLDATE DATE
);
INSERT INTO MEMBER_NOTNULL VALUES (1,'MMPR','1234','이자성','남','010-1344-1598','MMEE.NAVER.COM',SYSDATE);

SELECT * FROM MEMBER_NOTNULL;


/*
UNIQUE 제약조건 해당 컬럼에 중복된 데이터 값이 들어오는것을 제한
고유해야하는 데이터 (주민번호 아이디 이메일)에 적용
->NULL은 값이 없는 상태를 의미하므로 UNIQUE조건이 있어도 여러개 저장될수있음
보통 제약조건명을 지정하여 설정 에러 발생시 어떤 제약조건을 위배했는지 명확하게 파악하기위해
*/
--회원(MEMBER_UNIQUE) 회원아이데 UNIQUE 조건 설정

CREATE TABLE MEMBER_UNIQUE(
MEM_NO NUMBER NOT NULL,
MEM_ID VARCHAR2(20) NOT NULL,
MEM_PWD VARCHAR2(20) NOT NULL,
MEM_NAME VARCHAR2(20) NOT NULL,
GENDER CHAR(3),
PHONE CHAR(15),
EMAIL VARCHAR2(41),
ENROLLDATE DATE,
--컬럼 레벨방식 NOT NULL 번호 아이디 비밀번호 이름
---테이블 레벨 방식 UNIQUE(아이디)
CONSTRAINT UQ_MEM_ID UNIQUE(MEM_ID)
);

