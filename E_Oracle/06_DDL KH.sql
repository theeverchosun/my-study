/*
테이블 생성 CREATE TABLE
CREATE TABLE 테이블 명(
컬럼명 데이터 타입
컬럼명 데이터 타입 DEFAULT 기본값,
컬럼명 데이터 타입 제약조건,
컬럼명 데이터 타입 DEFAULT 기본값 제약조건,
);
오라클 기본 자료형 (데이터타입)
-날짜 DATE 날짜및 시간 데이터
-숫자 NUMBER 숫자데이터 (정수, 실수)
-문자 CHAR(크기) 고정길이 2000BYE까지 지정한크기보다 작으면 공백으로 채워짐
VARCHAR2 가변길이 최대 4000바이트까지 입력된 데이터의 실제길이만큼의 공간 차지
*/
--회원(MEMBER) : 회원번호(MEM_NO) 회원ID(MEM_ID) 회원비밀번호(MEM_PWD) 회원이름(MEM_NAME)
--성별(GENDER) 연락처(PHONE) 이메일(EMAIL) 가입일시(ENROLLDATE)
CREATE TABLE MEMBER(
MEM_NO NUMBER,
MEM_ID VARCHAR2(20),
MEM_PWD VARCHAR2(20),
MEM_NAME VARCHAR2(20),
GENDER CHAR(3),--남또는 여
PHONE CHAR(15),
EMAIL VARCHAR2(41),
ENROLLDATE DATE
);

