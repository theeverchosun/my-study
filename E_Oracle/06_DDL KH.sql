/*
PRIMARY KEY (기본키) 제약조건
:테이블 내에서 각 행 고유하게 식별하기 위해 사용되는 대표 컬럼을 지정
NOT NULL + UNIQUE(NULL사용불가 중복불가)
테이블당 오직 1개만 가능

*/
--회원 회원 번호 컬럼을 기본키로 지정
