/*
CHECK 제약 조건 해당 컬럼에 저장될수 있는 값범위나 특정 조건식을 지정해주는 규칙
조건식의 결과가 TRUE인 데이터만 저장할수있으며 NULL값도 저장 가능
*/
--회원(MEMBER_CHECK) : 성별(GENDER) '남' 또는 '여'값만 들어갈수있도록 조정
CREATE TABLE MEMBER_CHECK(
